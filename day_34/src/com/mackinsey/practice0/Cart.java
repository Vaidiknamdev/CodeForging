package com.mackinsey.practice0;

public class Cart {
	int productId;
	String productName;
	int price;
	int quantity;
	
	public Cart(int productId, String productName, int price, int quantity) {
		super();
		this.productId = productId;
		this.productName = productName;
		this.price = price;
		this.quantity = quantity;
	}
	
	
}
