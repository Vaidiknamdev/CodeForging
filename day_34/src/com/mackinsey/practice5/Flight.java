package com.mackinsey.practice5;

public class Flight {
	int flightNumber;
	String airLine;
	String destination;
	String departureTime;
	String status;
	public Flight(int flightNumber, String airLine, String destination, String departureTime, String status) {
		super();
		this.flightNumber = flightNumber;
		this.airLine = airLine;
		this.destination = destination;
		this.departureTime = departureTime;
		this.status = status;
	}
}
